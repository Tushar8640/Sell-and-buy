export interface FertilizerStage {
  stage: string; // যেমন: "জমি তৈরির সময়", "চারা রোপণের ২০ দিন পর"
  fertilizers: { name: string; amountPerDecimal: string; note?: string }[];
}

export interface CultivationGuide {
  landPrep: string; // জমি প্রস্তুতি
  seedRateAndTreatment: string; // বীজ হার ও শোধন
  spacing: string; // রোপণের দূরত্ব
  fertilizerSchedule: FertilizerStage[]; // সারের মাত্রা (শতাংশ প্রতি)
  irrigation: string; // সেচ ও পানি নিষ্কাশন
  weedingAndIntercare: string[]; // আগাছা ও অন্তর্বর্তীকালীন পরিচর্যা
  harvesting: string; // ফসল সংগ্রহ ও ফলন
}

export interface Medicine {
  tradeName: string; // বাণিজ্যিক নাম (যেমন: রিডোমিল গোল্ড)
  genericName: string; // সক্রিয় উপাদান / জেনেরিক নাম (যেমন: ম্যানকোজেব + মেটাল্যাক্সিল)
  dosage: string; // মাত্রা (যেমন: প্রতি লিটার পানিতে ২ গ্রাম)
  instructions: string; // ব্যবহারের নিয়ম (যেমন: বিকালে স্প্রে করতে হবে)
}

export interface DiseaseItem {
  id: string;
  name: string; // রোগ বা পোকার নাম
  type: "ছত্রাকজনিত রোগ" | "ব্যাকটেরিয়াজনিত রোগ" | "ভাইরাসজনিত রোগ" | "ক্ষতিকর পোকা";
  symptoms: string; // লক্ষণ
  organicRemedy: string; // জৈব বা প্রাকৃতিক প্রতিকার
  eradication: string[]; // নির্মূল বা দমনের উপায়
  medicines: Medicine[]; // অনুমোদিত রাসায়নিক বালাইনাশক
}

export interface CropAgronomy {
  cropId: string;
  cultivation: CultivationGuide;
  diseases: DiseaseItem[];
  safetyPrecautions: string[];
}

